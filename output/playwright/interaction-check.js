async (page) => {
  const origin = 'http://localhost:3100';
  const results = {};
  const errors = [];
  const backendRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if(request.url().includes('/api/') || request.url().includes(':4000')) backendRequests.push(request.url()); });
  await page.goto(origin + '/employee/packages');
  await page.locator('#upgrade-btn-O1').click();
  await page.keyboard.press('Escape');
  results.sheetFocusReturn = await page.locator('#upgrade-btn-O1').evaluate(element => element === document.activeElement);
  results.sheetScrollUnlocked = await page.evaluate(() => document.body.style.overflow !== 'hidden');
  await page.goto(origin + '/employee/tasks');
  await page.locator('input[type="file"]').setInputFiles('output/playwright/before/home-390x844.png');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'تأكيد وإرسال المهمة للاعتماد' }).click();
  await page.getByRole('button', { name: 'تحديث لقطة الشاشة المرفقة' }).waitFor();
  await page.getByRole('navigation').getByRole('link', { name: 'الرئيسية', exact: true }).click();
  await page.waitForURL(origin + '/employee');
  results.rewardCreditedOnce = (await page.locator('body').innerText()).includes('42.00');
  await page.getByRole('navigation').getByRole('link', { name: 'المهام', exact: true }).click();
  await page.waitForURL(origin + '/employee/tasks');
  await page.waitForFunction(() => { const image = document.querySelector('img[alt="معاينة لقطة الشاشة المرفوعة"]'); return image instanceof HTMLImageElement && image.naturalWidth > 0; });
  results.screenshotSurvivesNavigation = true;
  await page.screenshot({ path: 'output/playwright/after/tasks-submitted-route-return-390x844.png', fullPage: true });
  await page.getByRole('button', { name: 'إلغاء الصورة' }).click();
  await page.locator('input[type="file"]').setInputFiles('output/playwright/before/wallet-390x844.png');
  await page.getByRole('button', { name: 'تحديث لقطة الشاشة المرفقة' }).click();
  await page.getByRole('navigation').getByRole('link', { name: 'الرئيسية', exact: true }).click();
  await page.waitForURL(origin + '/employee');
  results.replacementDoesNotCreditAgain = (await page.locator('body').innerText()).includes('42.00');
  await page.goto(origin + '/employee/deposit');
  await page.getByRole('button', { name: 'تحديث الحالة' }).click();
  await page.getByRole('button', { name: 'تحديث الحالة' }).waitFor({ state: 'detached' });
  results.depositStatusUpdated = true;
  await page.goto(origin + '/employee/auth/verify-email?state=expired');
  await page.getByRole('heading', { name: 'رابط التفعيل غير صالح أو منتهي الصلاحية' }).waitFor();
  results.expiredVerification = await page.getByRole('heading', { name: 'رابط التفعيل غير صالح أو منتهي الصلاحية' }).isVisible();
  await page.getByRole('button', { name: 'طلب رابط تفعيل جديد' }).click();
  results.expiredResendKeepsExistingScreen = await page.getByRole('heading', { name: 'رابط التفعيل غير صالح أو منتهي الصلاحية' }).isVisible();
  await page.goto(origin + '/employee/auth/verify-email?state=inbox');
  await page.getByRole('button', { name: 'محاكاة الضغط على رابط التفعيل الوارد' }).click();
  await page.getByRole('heading', { name: 'تم تفعيل بريدك الإلكتروني بنجاح!' }).waitFor();
  results.linkVerificationCompletes = true;
  await page.goto(origin + '/employee/auth/reset-password?state=expired');
  await page.getByRole('link', { name: 'طلب رابط استعادة جديد' }).waitFor();
  results.expiredReset = await page.getByRole('heading', { name: 'رابط إعادة التعيين غير صالح أو منتهي' }).isVisible();
  await page.goto(origin + '/employee/auth/login');
  await page.getByRole('button', { name: 'إظهار كلمة المرور' }).click();
  results.passwordVisibility = await page.locator('input[type="text"]').count() > 0;
  await page.getByRole('button', { name: 'تسجيل الدخول', exact: true }).click();
  await page.waitForURL(origin + '/employee');
  await page.goBack();
  results.loginPushHistory = page.url() === origin + '/employee/auth/login';
  return { results, errors, backendRequests };
}
